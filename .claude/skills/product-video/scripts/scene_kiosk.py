import sys, time
sys.path.insert(0, sys.path[0])
from rec import Browser, Recorder, scan

b = Browser()
b.viewport(1024, 600)
b.go("/kiosk/")
b.tap("a.nav-btn[data-mode=order]", pause=0)
b.wait_state("wait_for_card")
time.sleep(1.5)

r = Recorder("kiosk_wait")
time.sleep(12)
r.stop()

r = Recorder("kiosk_order")
time.sleep(2.5)
scan("Anna")
b.wait_state("order:")
time.sleep(1.5)
b.tap("label.coffee-option:nth-of-type(2)")
time.sleep(1.2)
b.tap("button.primary-action")
b.wait_state("thank_you")
r.stop(hold=4.5)

r = Recorder("kiosk_ranking")
b.tap("a.nav-btn[data-mode=ranking]")
b.wait_state("ranking")
time.sleep(5)
b.tap(".ranking-tabs a[href$='/ranking/month/']")
time.sleep(4)
b.tap(".ranking-tabs a[href$='/ranking/pillory/']")
time.sleep(4)
r.stop()

r = Recorder("kiosk_pay")
b.tap("a.nav-btn[data-mode=info]")
b.wait_state("wait_for_card")
time.sleep(1.5)
scan("David")
b.wait_state("info_pay")
time.sleep(2.5)
b.js("(() => { const el = [...document.querySelectorAll('#panel *')].find(e => e.scrollHeight > e.clientHeight + 20 && getComputedStyle(e).overflowY !== 'visible'); el && el.scrollTo({top: el.scrollHeight, behavior: 'smooth'}); })()")
time.sleep(4)
r.stop()
b.tap("a.nav-btn[data-mode=order]", pause=0)
